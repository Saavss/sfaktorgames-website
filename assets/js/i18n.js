function setLanguage(lang) {
  if (!translations[lang]) lang = "tr";
  localStorage.setItem("sfaktor_lang", lang);
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    const value = translations[lang][key];
    if (value !== undefined) el.innerHTML = value.replace(/\n/g, "<br>");
  });
  const current = document.getElementById("currentLang");
  if (current) current.textContent = lang.toUpperCase();
  document.querySelector(".lang-menu")?.classList.remove("open");
  document.dispatchEvent(new CustomEvent("sfaktorLanguageChanged", {detail:{lang}}));
}

document.addEventListener("DOMContentLoaded", () => {
  const queryLang = new URLSearchParams(location.search).get("lang");
  const saved = Object.keys(translations).includes(queryLang) ? queryLang : (localStorage.getItem("sfaktor_lang") || "tr");
  setLanguage(saved);

  const btn = document.querySelector(".lang-btn");
  const menu = document.querySelector(".lang-menu");
  if (btn && menu) btn.addEventListener("click", () => menu.classList.toggle("open"));
  document.querySelectorAll("[data-lang]").forEach(btn => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
  });
});
